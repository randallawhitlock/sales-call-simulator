/**
 * Generates ./servers/<server>/<tool>.ts — one typed wrapper per MCP tool —
 * so the agent discovers tools by browsing files instead of loading every
 * definition into context.
 *
 *   npm run codegen
 */
import fs from "node:fs";
import path from "node:path";
import type { Tool } from "@modelcontextprotocol/sdk/types.js";
import { SERVERS_DIR, isMain } from "./config.ts";
import { McpHost } from "./host.ts";
import { oneLine, schemaToTs } from "./schema-to-ts.ts";

export function slug(s: string): string {
  return s.replace(/[^A-Za-z0-9]+/g, "-").replace(/^-|-$/g, "").toLowerCase() || "x";
}

export function camel(s: string): string {
  const parts = s.split(/[^A-Za-z0-9]+/).filter(Boolean);
  const out = parts.map((p, i) => (i === 0 ? p[0].toLowerCase() + p.slice(1) : p[0].toUpperCase() + p.slice(1))).join("");
  return /^[0-9]/.test(out) ? `_${out}` : out || "tool";
}

const pascal = (s: string) => camel(s)[0].toUpperCase() + camel(s).slice(1);

export function renderTool(server: string, tool: Tool): string {
  const fn = camel(tool.name);
  const T = pascal(tool.name);
  const input = schemaToTs(tool.inputSchema as never);
  const output = tool.outputSchema ? schemaToTs(tool.outputSchema as never) : "any";
  const doc = tool.description ? oneLine(tool.description) : `${server}.${tool.name}`;
  const hasRequired = ((tool.inputSchema as { required?: string[] }).required ?? []).length > 0;
  return `// Generated by code-mode codegen. Do not edit.
import { callMCPTool } from "#runtime/client.ts";

export type ${T}Input = ${input === "any" ? "Record<string, any>" : input};
export type ${T}Output = ${output};

/** ${doc} */
export async function ${fn}(input: ${T}Input${hasRequired ? "" : " = {}"}): Promise<${T}Output> {
  return callMCPTool(${JSON.stringify(server)}, ${JSON.stringify(tool.name)}, input);
}
`;
}

export async function generate(host: McpHost, outDir = SERVERS_DIR): Promise<{ server: string; tools: number }[]> {
  fs.rmSync(outDir, { recursive: true, force: true });
  fs.mkdirSync(outDir, { recursive: true });
  const summary: { server: string; tools: number }[] = [];
  for (const server of Object.keys(host.config.servers)) {
    const tools = await host.listTools(server);
    const dir = path.join(outDir, slug(server));
    fs.mkdirSync(dir, { recursive: true });
    const index: string[] = [];
    const seen = new Set<string>();
    for (const tool of tools) {
      let file = camel(tool.name);
      while (seen.has(file)) file += "_";
      seen.add(file);
      fs.writeFileSync(path.join(dir, `${file}.ts`), renderTool(server, tool));
      index.push(`export * from "./${file}.ts";`);
    }
    fs.writeFileSync(path.join(dir, "index.ts"), index.join("\n") + "\n");
    summary.push({ server, tools: tools.length });
  }
  return summary;
}

if (isMain(import.meta.url)) {
  const host = new McpHost();
  try {
    for (const { server, tools } of await generate(host)) console.log(`servers/${slug(server)}: ${tools} tools`);
  } finally {
    await host.close();
  }
}
